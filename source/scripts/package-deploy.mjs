#!/usr/bin/env node
// Builds a deployable package in E:/Sitrak-deploy/<timestamp> for the cPanel/Node host.
// Usage: node scripts/package-deploy.mjs
import {cp, mkdir, readFile, writeFile, readdir, stat} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {join, relative, sep} from 'node:path';
import {legacyRedirects} from '../lib/redirect-rules.ts';

const ROOT = process.cwd();
const stamp = new Date().toISOString().replaceAll(':','-').replaceAll('.','-').slice(0,19);
const OUT = join('E:/Sitrak-deploy', stamp);

const sha256 = async (file) => createHash('sha256').update(await readFile(file)).digest('hex');

async function walk(dir, out = []) {
  for (const entry of await readdir(dir, {withFileTypes: true})) {
    const full = join(dir, entry.name);
    if (entry.isDirectory()) await walk(full, out);
    else out.push(full);
  }
  return out;
}

const skip = (source) => source.split(sep).some((part) => ['cache', 'dev', 'trace'].includes(part));

console.log('building package in', OUT);
await mkdir(OUT, {recursive: true});

// 1. compiled app: everything but caches
await cp(join(ROOT, '.next'), join(OUT, '.next'), {recursive: true, filter: (src) => !skip(relative(ROOT, src))});
// 2. public assets, manifest and lock
await cp(join(ROOT, 'public'), join(OUT, 'public'), {recursive: true});
await cp(join(ROOT, 'package.json'), join(OUT, 'package.json'));
await cp(join(ROOT, 'package-lock.json'), join(OUT, 'package-lock.json'));

// 3. runtime config with the redirect map embedded (no TypeScript needed on the server)
const redirects = legacyRedirects.map(({source, destination}) => ({source, destination, permanent: true}));
await writeFile(join(OUT, 'next.config.mjs'), `// Generated by scripts/package-deploy.mjs — mirrors lib/redirect-rules.ts.
const redirects = ${JSON.stringify(redirects, null, 2)};

/** @type {import('next').NextConfig} */
const nextConfig = {
  distDir: '.next',
  redirects() {
    return redirects;
  },
};

export default nextConfig;
`);

// 4. cPanel Node.js entry point. The platform assigns PORT and proxies to this process.
await writeFile(join(OUT, 'app.cjs'), `#!/usr/bin/env node
// cPanel / Passenger entry point for the Truk Afrik site.
// Passenger sets PORT; we hand it to the standard Next.js production server.
const {spawn} = require('node:child_process');

const port = process.env.PORT || process.env.NODE_PORT || 3000;
const nextBin = require.resolve('next/dist/bin/next');
const child = spawn(process.execPath, [nextBin, 'start', '-p', String(port)], {
  stdio: 'inherit',
  env: {...process.env, NODE_ENV: 'production'},
});

const stop = () => {
  child.kill('SIGTERM');
  process.exit(0);
};
process.on('SIGTERM', stop);
process.on('SIGINT', stop);
child.on('exit', (code) => process.exit(code ?? 0));
`);

// 5. Apache privacy guard: never serve source, build internals or the manifest.
await writeFile(join(OUT, '.htaccess'), `# Truk Afrik — privacy guard for the Node application root
<FilesMatch "^(package\\.json|package-lock\\.json|app\\.cjs|next\\.config\\.mjs|deployment-manifest\\.json)$">
  Require all denied
</FilesMatch>
RedirectMatch 404 ^/\\.next/
RedirectMatch 404 ^/server/
Options -Indexes
`);

// 6. activation notes for whoever configures cPanel
await writeFile(join(OUT, 'DEPLOYMENT.md'), `# Deployment package — ${stamp}

This directory is ready to sit in the cPanel Node application root.

## Upload target
\`/home/trukafri/public_html/trukafrik.com\` on \`cp61.domains.co.za\` (FTPS, port 21).

## Activate
1. cPanel → *Setup Node.js App* → application root this directory, mode production, startup file \`app.cjs\`, Node 20+.
2. In the virtualenv terminal: \`npm ci --omit=dev\` (do **not** upload Windows \`node_modules\`).
3. Set private environment variables (not in files):
   - \`SMTP_HOST\`, \`SMTP_PORT\`, \`SMTP_SECURE\`, \`SMTP_USER\`, \`SMTP_PASS\`, \`SMTP_FROM\`
   - \`ENQUIRY_PUBLIC_ORIGIN=https://www.trukafrik.com\`
4. Restart the application, then confirm:
   - \`/\` renders, \`/about\`, \`/finance\`, \`/parts\`, \`/pre-owned\`, \`/privacy-policy\` render
   - \`/sitemap.xml\` and \`/robots.txt\` return 200
   - \`/about-us\` returns 308 to \`/about\` and \`/parts---nelspruit\` 308s to \`/parts\`
   - \`/package.json\`, \`/app.cjs\`, \`/deployment-manifest.json\` and \`/.next/...\` return 403/404
5. DNS/HTTPS cutover is separate: the public domain must point at this host before the site is live.
`);

// 7. manifest for integrity checks after upload
const files = await walk(OUT);
const manifest = [];
for (const file of files) {
  if (file.endsWith('deployment-manifest.json')) continue;
  manifest.push({path: relative(OUT, file).split(sep).join('/'), bytes: (await stat(file)).size, sha256: await sha256(file)});
}
const manifestBody = JSON.stringify({generated: new Date().toISOString(), root: OUT, files: manifest}, null, 1);
await writeFile(join(OUT, 'deployment-manifest.json'), manifestBody);
console.log('files:', manifest.length, 'bytes:', manifest.reduce((sum, f) => sum + f.bytes, 0));
console.log('MANIFEST', await sha256(join(OUT, 'deployment-manifest.json')));
